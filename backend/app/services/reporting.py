def rpt_audit(db, scope, start, end, facility_id) -> Rows:
    q = scope.apply(db.query(AuditLog), AuditLog.facility_id)  # supervisors: own region only
    if facility_id:
        q = q.filter(AuditLog.facility_id == facility_id)
    q = _range(q, AuditLog.timestamp, start, end).order_by(AuditLog.timestamp)
    return ("Audit trail", ["Timestamp", "Actor", "Role", "Action", "Category", "Outcome", "Entity", "Entity ID", "IP",
                            "Details"],
            [[a.timestamp, a.actor_name, a.actor_role, a.action, a.category, a.outcome, a.entity_type, str(a.entity_id),
              a.ip_address, str(a.details)[:400]] for a in q.limit(100000)])


def rpt_compliance(db, scope, start, end, facility_id) -> Rows:
    from app.services.analytics import facility_comparison
    days = max(1, ((end or datetime.now(timezone.utc)) - (start or datetime.now(timezone.utc) - timedelta(days=30))).days)
    rows = facility_comparison(db, scope, days)
    if facility_id:
        rows = [r for r in rows if r["facility_id"] == facility_id]
    return ("Facility compliance summary", ["Facility", "Code", "Compliance % (14d)", "Readings", "Excursions",
                                            "Incidents", "MTTA (min)", "MTTR (h)", "Equipment work orders"],
            [[r["facility_name"], r["code"], r["compliance"], r["readings"], r["excursions"], r["incidents"],
              r["mtta_min"], r["mttr_h"], r["equipment_failures"]] for r in rows])


def rpt_device_reliability(db, scope, start, end, facility_id) -> Rows:
    from app.services.analytics import device_reliability
    rows = device_reliability(db, scope)
    if facility_id:
        rows = [r for r in rows if r["facility_id"] == facility_id]
    return ("Device reliability (24h)", ["Sensor", "Unit", "Status", "Readings", "Expected", "Availability %", "Battery %",
                                         "Simulated"],
            [[r["sensor_code"], r["storage_unit_code"], r["status"], r["readings"], r["expected"], r["availability"],
              r["battery_level"], r["is_simulated"]] for r in rows])


REPORTS: Dict[str, Dict[str, Any]] = {
    "temperature": {"label": "Daily temperature records", "permission": "monitoring.view", "fn": rpt_temperature},
    "incidents": {"label": "Incident & corrective-action history", "permission": "incidents.view", "fn": rpt_incidents},
    "inventory_movements": {"label": "Inventory movement ledger", "permission": "inventory.view", "fn": rpt_movements},
    "stock": {"label": "Vaccine stock status", "permission": "inventory.view", "fn": rpt_stock},
    "maintenance": {"label": "Maintenance history", "permission": "maintenance.view", "fn": rpt_maintenance},
    "calibration": {"label": "Calibration records", "permission": "calibration.view", "fn": rpt_calibration},
    "compliance": {"label": "Facility compliance & comparison", "permission": "incidents.view", "fn": rpt_compliance},
    "device_reliability": {"label": "Device reliability", "permission": "devices.view", "fn": rpt_device_reliability},
    "audit": {"label": "Audit trail", "permission": "audit.view", "fn": rpt_audit},
}


def available_reports(scope) -> List[dict]:
    return [{"key": k, "label": v["label"]} for k, v in REPORTS.items() if scope.has(v["permission"])]


def build(db: Session, scope, key: str, fmt: str, start: Optional[datetime], end: Optional[datetime],
          facility_id=None) -> Tuple[str, bytes, str]:
    spec = REPORTS[key]
    fn: Callable = spec["fn"]
    title, headers, rows = fn(db, scope, start, end, facility_id)
    meta = {"Generated": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
            "By": f"{scope.user.name} ({scope.user.role.value})",
            "Period": f"{start.date() if start else 'start'} → {end.date() if end else 'now'}",
            "Scope": "All facilities" if scope.is_global else f"{len(scope.facility_ids)} assigned facilities",
            "Rows": str(len(rows))}
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    if fmt == "pdf":
        return f"coldguard_{key}_{stamp}.pdf", ReportingService.to_pdf(title, headers, rows, meta), "application/pdf"
    return f"coldguard_{key}_{stamp}.csv", ReportingService.to_csv(title, headers, rows, meta), "text/csv"
