def rpt_calibration(db, scope, start, end, facility_id) -> Rows:
    q = (db.query(CalibrationRecord, Sensor.sensor_code).join(Sensor, Sensor.id == CalibrationRecord.sensor_id)
         .join(StorageUnit, StorageUnit.id == Sensor.storage_unit_id))
