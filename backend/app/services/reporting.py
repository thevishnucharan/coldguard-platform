"""Report generation (CSV / PDF). Each report type declares the permission it requires and
builds rows ONLY from facilities inside the caller's AccessScope.

CSV formula-injection protection preserved from v1.
"""
from __future__ import annotations

import csv
import io
from datetime import datetime, timedelta, timezone
from typing import Any, Callable, Dict, List, Optional, Tuple

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
from sqlalchemy.orm import Session

from app.db.base import as_utc
from app.models import (AuditLog, Batch, CalibrationRecord, Incident, InventoryMovement, MaintenanceTicket, Sensor,
                        StorageUnit, TemperatureReading)

Rows = Tuple[str, List[str], List[List[Any]]]


class ReportingService:
    DISCLAIMER = ("Operational record generated by ColdGuard. Not a regulatory certification. "
                  "Simulated data, where present, is flagged in the 'Simulated' column.")

    @staticmethod
    def _sanitize_csv_value(value: Any) -> Any:
        if isinstance(value, str) and value and value[0] in ("=", "+", "-", "@", "\t", "\r"):
            return f"'{value}"
        return value

    @staticmethod
    def _fmt(v: Any) -> Any:
        if isinstance(v, datetime):
            return as_utc(v).strftime("%Y-%m-%d %H:%M:%S UTC")
        if hasattr(v, "value"):
            return v.value
        if isinstance(v, float):
            return round(v, 3)
        return "" if v is None else v

    @classmethod
    def to_csv(cls, title: str, headers: List[str], rows: List[List[Any]], meta: Dict[str, str]) -> bytes:
        out = io.StringIO()
        w = csv.writer(out)
        w.writerow([title])
        for k, v in meta.items():
            w.writerow([k, cls._sanitize_csv_value(str(v))])
        w.writerow([cls.DISCLAIMER])
        w.writerow([])
        w.writerow(headers)
        for r in rows:
            w.writerow([cls._sanitize_csv_value(cls._fmt(v)) if isinstance(cls._fmt(v), str) else cls._fmt(v) for v in r])
        return out.getvalue().encode("utf-8")

    @classmethod
    def to_pdf(cls, title: str, headers: List[str], rows: List[List[Any]], meta: Dict[str, str]) -> bytes:
        buf = io.BytesIO()
        doc = SimpleDocTemplate(buf, pagesize=landscape(A4), leftMargin=28, rightMargin=28, topMargin=28,
                                bottomMargin=28, title=title)
        st = getSampleStyleSheet()
        small = st["BodyText"].clone("small", fontSize=7, leading=8.5)
        story = [Paragraph(f"ColdGuard — {title}", st["Title"]),
                 Paragraph(" | ".join(f"<b>{k}:</b> {v}" for k, v in meta.items()), st["BodyText"]),
                 Paragraph(f"<i>{cls.DISCLAIMER}</i>", small), Spacer(1, 8)]
        data = [[Paragraph(f"<b>{h}</b>", small) for h in headers]]
        for r in rows[:2000]:
            data.append([Paragraph(str(cls._fmt(v))[:300].replace("&", "&amp;").replace("<", "&lt;"), small) for v in r])
        if len(rows) > 2000:
            story.append(Paragraph(f"Showing first 2000 of {len(rows)} rows — use CSV for the full dataset.", small))
        t = Table(data, repeatRows=1)
        t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f2a43")),
                               ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                               ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")),
                               ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f1f5f9")]),
                               ("VALIGN", (0, 0), (-1, -1), "TOP")]))
        story.append(t)
        doc.build(story)
        return buf.getvalue()


# --------------------------------------------------------------------------- report builders
def _range(q, col, start, end):
    if start:
        q = q.filter(col >= start)
    if end:
        q = q.filter(col <= end)
    return q


def rpt_temperature(db, scope, start, end, facility_id) -> Rows:
    q = (db.query(TemperatureReading, StorageUnit.unit_code, Sensor.sensor_code)
         .join(StorageUnit, StorageUnit.id == TemperatureReading.storage_unit_id)
         .join(Sensor, Sensor.id == TemperatureReading.sensor_id))
    q = scope.apply(q, StorageUnit.facility_id)
    if facility_id:
        q = q.filter(StorageUnit.facility_id == facility_id)
    q = _range(q, TemperatureReading.timestamp, start, end).order_by(TemperatureReading.timestamp).limit(100000)
    return ("Temperature records", ["Timestamp", "Storage unit", "Sensor", "Temperature °C", "Quality", "Source", "Simulated"],
            [[r.timestamp, u, s, r.temperature, r.quality_status, r.source, r.is_simulated] for r, u, s in q])


def rpt_incidents(db, scope, start, end, facility_id) -> Rows:
    q = scope.apply(db.query(Incident), Incident.facility_id)
    if facility_id:
        q = q.filter(Incident.facility_id == facility_id)
    q = _range(q, Incident.created_at, start, end).order_by(Incident.created_at)
    rows = []
    for i in q:
        cas = "; ".join(f"[{c.status.value}] {c.description}" for c in i.corrective_actions)
        rows.append([i.incident_number, i.incident_type, i.severity, i.status, i.facility.name if i.facility else "",
                     i.storage_unit.unit_code if i.storage_unit else "", i.created_at, i.acknowledged_at, i.resolved_at,
                     i.closed_at, i.root_cause, cas, i.review_decision, i.vaccine_disposition, i.escalation_level,
                     i.is_simulated])
    return ("Incident & corrective-action history",
            ["Incident", "Type", "Severity", "Status", "Facility", "Unit", "Detected", "Acknowledged", "Resolved",
             "Closed", "Root cause", "Corrective actions", "Review decision", "Vaccine disposition", "Escalation",
             "Simulated"], rows)


def rpt_movements(db, scope, start, end, facility_id) -> Rows:
    q = scope.apply(db.query(InventoryMovement, Batch.batch_number).join(Batch, Batch.id == InventoryMovement.batch_id),
                    InventoryMovement.facility_id)
    if facility_id:
        q = q.filter(InventoryMovement.facility_id == facility_id)
    q = _range(q, InventoryMovement.created_at, start, end).order_by(InventoryMovement.created_at)
    return ("Inventory movement ledger", ["Timestamp", "Batch", "Movement", "Change", "Quantity after", "Status before",
                                         "Status after", "Reason", "Reference", "Performed by"],
            [[m.created_at, b, m.movement_type, m.quantity_change, m.quantity_after, m.status_before, m.status_after,
              m.reason, m.reference, m.performed_by_name] for m, b in q])


def rpt_stock(db, scope, start, end, facility_id) -> Rows:
    q = scope.apply(db.query(Batch), Batch.facility_id)
    if facility_id:
        q = q.filter(Batch.facility_id == facility_id)
