import { AlertOctagon, AlertTriangle, CheckCircle2, CircleDashed, CircleSlash, FlaskConical, Info, WifiOff } from 'lucide-react'
import { cx, humanize } from '../../utils/format'

type Tone = 'ok' | 'warn' | 'serious' | 'crit' | 'info' | 'neutral' | 'brand'
const TONE: Record<Tone, string> = {
  ok: 'bg-ok-bg text-ok-ink ring-ok/25',
  warn: 'bg-warn-bg text-warn-ink ring-warn/40',
  serious: 'bg-serious-bg text-serious-ink ring-serious/30',
  crit: 'bg-crit-bg text-crit-ink ring-crit/25',
  info: 'bg-info-bg text-info-ink ring-series-1/20',
  neutral: 'bg-canvas text-ink-2 ring-line',
  brand: 'bg-brand-50 text-brand-700 ring-brand-200',
}

export function Pill({ tone = 'neutral', icon: Icon, children, className, title }: {
  tone?: Tone; icon?: React.ComponentType<{ size?: number }>; children: React.ReactNode; className?: string; title?: string
}) {
  return (
    <span title={title} className={cx('inline-flex items-center gap-1 rounded-md px-1.5 py-0.5 text-[11.5px] font-medium ring-1 ring-inset whitespace-nowrap', TONE[tone], className)}>
      {Icon && <Icon size={12} />}
      {children}
    </span>
  )
}

const HEALTH: Record<string, [Tone, React.ComponentType<{ size?: number }>, string]> = {
  NORMAL: ['ok', CheckCircle2, 'Normal'],
  WARNING: ['warn', AlertTriangle, 'Warning'],
  CRITICAL: ['crit', AlertOctagon, 'Critical'],
  OFFLINE: ['crit', WifiOff, 'Offline'],
  MISSING_TELEMETRY: ['serious', CircleDashed, 'Missing data'],
  NO_DATA: ['neutral', CircleDashed, 'No data'],
  INACTIVE: ['neutral', CircleSlash, 'Inactive'],
}
export function HealthBadge({ health }: { health: string }) {
  const [tone, Icon, label] = HEALTH[health] || ['neutral', Info, humanize(health)]
  return <Pill tone={tone} icon={Icon}>{label}</Pill>
}
export const healthColor = (h: string) =>
  ({ NORMAL: 'var(--color-ok)', WARNING: 'var(--color-warn)', CRITICAL: 'var(--color-crit)', OFFLINE: 'var(--color-crit)',
     MISSING_TELEMETRY: 'var(--color-serious)' } as Record<string, string>)[h] || 'var(--color-ink-3)'

export function SeverityBadge({ severity }: { severity: string }) {
  const map: Record<string, [Tone, React.ComponentType<{ size?: number }>]> = {
    CRITICAL: ['crit', AlertOctagon], HIGH: ['serious', AlertTriangle], WARNING: ['warn', AlertTriangle],
  }
  const [tone, Icon] = map[severity] || ['neutral', Info]
  return <Pill tone={tone} icon={Icon}>{humanize(severity)}</Pill>
}

const STATUS_TONE: Record<string, Tone> = {
  DETECTED: 'crit', OPEN: 'crit', ACKNOWLEDGED: 'warn', INVESTIGATING: 'warn', CORRECTIVE_ACTION_PENDING: 'info',
  UNDER_REVIEW: 'info', RESOLVED: 'ok', CLOSED: 'neutral',
  ASSIGNED: 'info', IN_PROGRESS: 'warn', VERIFIED: 'ok',
  ACTIVE: 'ok', QUARANTINED: 'serious', EXPIRED: 'crit', DEPLETED: 'neutral', DISCARDED: 'neutral', COMPLETED: 'neutral',
  PROPOSED: 'info', APPROVED: 'ok', REJECTED: 'crit', REVISION_REQUESTED: 'warn', IMPLEMENTED: 'brand',
  ONLINE: 'ok', ERROR: 'crit', CALIBRATING: 'info', PROVISIONED: 'neutral', DECOMMISSIONED: 'neutral',
  PASS: 'ok', FAIL: 'crit', ADJUSTED: 'warn', SUCCESS: 'ok', FAILURE: 'crit', DENIED: 'serious',
}
export function StatusPill({ status, label }: { status: string; label?: string }) {
  const tone = STATUS_TONE[status] || 'neutral'
  const short: Record<string, string> = { CORRECTIVE_ACTION_PENDING: 'Action pending', MISSING_TELEMETRY: 'Missing data' }
  return <Pill tone={tone}>{label || short[status] || humanize(status)}</Pill>
}

export function PriorityBadge({ priority }: { priority: string }) {
  const tone: Tone = priority === 'URGENT' ? 'crit' : priority === 'HIGH' ? 'serious' : priority === 'MEDIUM' ? 'warn' : 'neutral'
  return <Pill tone={tone}>{humanize(priority)}</Pill>
}

export function SimulatedTag({ show = true }: { show?: boolean }) {
  if (!show) return null
  return <Pill tone="info" icon={FlaskConical} title="Generated by the demo simulator — not real hardware">Simulated</Pill>
}

export function SourceTag({ source }: { source: string }) {
  const m: Record<string, [Tone, string]> = {
    RULE: ['neutral', 'Threshold rule'], ML: ['brand', 'ML signal'], STATISTICAL: ['brand', 'Statistical'], MANUAL: ['neutral', 'Reported'],
    PREVENTIVE: ['neutral', 'Preventive'],
  }
  const [tone, label] = m[source] || ['neutral', humanize(source)]
  return <Pill tone={tone}>{label}</Pill>
}
