import { CheckCircle2, ClipboardCheck, Hammer, Paperclip, Play, Search, UserPlus } from 'lucide-react'
import { useState } from 'react'
import toast from 'react-hot-toast'
import { Link, useParams } from 'react-router-dom'
import { Card, CardHeader } from '../../components/common/Card'
import { ErrorState, PageSkeleton } from '../../components/common/Feedback'
import { Field } from '../../components/common/Form'
import { ConfirmDialog, Modal } from '../../components/common/Modal'
import { PageHeader } from '../../components/common/PageHeader'
import { Pill, PriorityBadge, SourceTag, StatusPill } from '../../components/common/Status'
import { useApi } from '../../hooks/useApi'
import { errorMessage } from '../../services/api/client'
import { Maintenance, Users } from '../../services/api/endpoints'
import { useAuthStore } from '../../store/authStore'
import { cx, fmtDate, fmtDateTime, humanize } from '../../utils/format'

const STEPS = ['OPEN', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'VERIFIED', 'CLOSED']

export default function WorkOrderDetailPage() {
  const { id = '' } = useParams()
  const { can, me } = useAuthStore()
  const q = useApi(() => Maintenance.get(id), [id], { refreshOn: ['maintenance.updated'] })
  const [dlg, setDlg] = useState<null | 'assign' | 'note' | 'inspection' | 'evidence' | 'resolve' | 'verify' | 'fail' | 'close'>(null)
  const t = q.data
  if (q.loading && !t) return <PageSkeleton />
  if (q.error || !t) return <ErrorState message={q.error || 'Work order not found'} onRetry={q.reload} />
  const act = async (action: string, body?: Record<string, unknown>, ok = 'Updated') => {
    try { q.setData(await Maintenance.act(id, action, body)); toast.success(ok) } catch (e) { toast.error(errorMessage(e)); throw e }
  }
  const mine = t.assigned_to === me?.id
  const tech = can('maintenance.update')
  const stepIdx = STEPS.indexOf(t.status)

  return (
    <>
      <PageHeader title={t.ticket_number} subtitle={t.title} crumbs={[{ label: 'Maintenance', to: '/maintenance' }, { label: t.ticket_number }]}
        meta={<><StatusPill status={t.status} /><PriorityBadge priority={t.priority} /><Pill>{humanize(t.maintenance_type)}</Pill><SourceTag source={t.trigger} />
          {t.is_overdue && <Pill tone="crit">Overdue</Pill>}</>}
        actions={<>
          {can('maintenance.assign') && ['OPEN', 'ASSIGNED'].includes(t.status) && <button className="btn-secondary" onClick={() => setDlg('assign')}><UserPlus size={15} /> Assign technician</button>}
          {tech && t.status === 'OPEN' && <button className="btn-primary" onClick={() => act('accept', undefined, 'Work order accepted')}><ClipboardCheck size={15} /> Accept</button>}
          {tech && mine && t.status === 'ASSIGNED' && <button className="btn-primary" onClick={() => act('start', undefined, 'Work started')}><Play size={15} /> Start work</button>}
          {tech && mine && t.status === 'IN_PROGRESS' && <>
            <button className="btn-secondary" onClick={() => setDlg('inspection')}><Search size={15} /> Inspection result</button>
            <button className="btn-secondary" onClick={() => setDlg('evidence')}><Paperclip size={15} /> Evidence</button>
            <button className="btn-primary" onClick={() => setDlg('resolve')}><Hammer size={15} /> Record repair</button></>}
          {can('maintenance.verify') && !mine && t.status === 'RESOLVED' && <>
            <button className="btn-secondary" onClick={() => setDlg('fail')}>Not fixed</button>
            <button className="btn-primary" onClick={() => setDlg('verify')}><CheckCircle2 size={15} /> Verify operation</button></>}
          {can('maintenance.verify') && t.status === 'VERIFIED' && <button className="btn-primary" onClick={() => setDlg('close')}>Close</button>}
        </>} />

      <ol className="card card-pad mb-4 grid grid-cols-6 gap-2" aria-label="Work-order progress">
        {STEPS.map((s, i) => (
          <li key={s} className="text-center">
            <div className={cx('h-1.5 rounded-full', i <= stepIdx ? 'bg-brand-500' : 'bg-line')} />
            <div className={cx('mt-1.5 text-[11px]', i === stepIdx ? 'font-semibold text-ink' : 'text-ink-3')}>{humanize(s)}</div>
          </li>
        ))}
      </ol>

      <div className="grid xl:grid-cols-[1fr_340px] gap-4">
        <div className="space-y-4 min-w-0">
          <Card><CardHeader title="Issue description" /><p className="text-[13px] whitespace-pre-wrap text-ink-2">{t.description}</p>
            {t.trigger !== 'MANUAL' && <p className="text-xs text-ink-3 mt-3">Auto-generated by <b>{humanize(t.trigger)}</b> trigger{t.trigger_rule && <> — rule <span className="mono">{t.trigger_rule}</span></>}. {t.trigger === 'ML' ? 'Model-based decision support.' : 'Deterministic rule, not a prediction.'}</p>}
          </Card>
          {(t.inspection_results || t.repair_notes) && (
            <Card><CardHeader title="Inspection & repair" />
              {t.inspection_results && <><p className="label">Inspection results</p><p className="text-[13px] whitespace-pre-wrap mb-3">{t.inspection_results}</p></>}
              {t.repair_notes && <><p className="label">Repair notes</p><p className="text-[13px] whitespace-pre-wrap">{t.repair_notes}</p></>}
            </Card>)}
          <Card>
            <CardHeader title="Service log" actions={(tech || can('maintenance.create')) && t.status !== 'CLOSED' && <button className="btn-secondary btn-sm" onClick={() => setDlg('note')}>Add note</button>} />
            <ul className="space-y-3">
              {(t.notes || []).map((n) => (
                <li key={n.id} className="flex gap-3">
                  <Pill tone={n.kind === 'STATUS' ? 'neutral' : n.kind === 'REPAIR' ? 'brand' : n.kind === 'INSPECTION' ? 'info' : n.kind === 'EVIDENCE' ? 'warn' : 'neutral'} className="h-fit">{humanize(n.kind)}</Pill>
                  <div className="min-w-0">
                    <p className="text-[13px] whitespace-pre-wrap">{n.body}</p>
                    {n.evidence_reference && <p className="text-xs text-brand-700 mono mt-0.5">{n.evidence_reference}</p>}
                    <p className="text-[11px] text-ink-3 mt-0.5">{n.author_name} · {fmtDateTime(n.created_at)}</p>
                  </div>
                </li>
              ))}
            </ul>
          </Card>
        </div>
        <Card>
          <CardHeader title="Details" />
          <dl className="text-[13px] space-y-2">
            {([['Facility', t.facility_name], ['Equipment', t.storage_unit_id ? <Link className="text-brand-700" to={`/monitoring/units/${t.storage_unit_id}`}>{t.storage_unit_code}</Link> : '—'],
              ['Sensor', t.sensor_code], ['Related incident', t.incident_id ? <Link className="text-brand-700" to={`/incidents/${t.incident_id}`}>View incident</Link> : '—'],
              ['Technician', t.assignee_name || 'Unassigned'], ['Created', fmtDateTime(t.created_at)], ['Due', fmtDate(t.due_date)],
              ['Resolved', fmtDateTime(t.resolved_at)], ['Verified', fmtDateTime(t.verified_at)], ['Next maintenance', fmtDate(t.next_maintenance_due)]] as [string, React.ReactNode][]).map(([k, v]) => (
              <div key={k} className="flex justify-between gap-2 border-b border-line pb-2 last:border-0"><dt className="text-ink-3">{k}</dt><dd className="text-right">{v || '—'}</dd></div>
            ))}
          </dl>
        </Card>
      </div>

      <AssignTech open={dlg === 'assign'} onClose={() => setDlg(null)} facilityId={t.facility_id} onSubmit={(tid) => act('assign', { technician_id: tid }, 'Technician assigned')} />
      <ConfirmDialog open={dlg === 'note'} onClose={() => setDlg(null)} title="Add service note" reasonLabel="Note" reasonRequired minReason={2} confirmLabel="Add"
        onConfirm={(b) => act('notes', { body: b, kind: 'NOTE' }, 'Note added')} />
      <ConfirmDialog open={dlg === 'inspection'} onClose={() => setDlg(null)} title="Record inspection result" reasonLabel="Findings" reasonRequired minReason={2} confirmLabel="Save"
        onConfirm={(b) => act('notes', { body: b, kind: 'INSPECTION' }, 'Inspection recorded')} />
      <EvidenceDialog open={dlg === 'evidence'} onClose={() => setDlg(null)} onSubmit={(body, ref) => act('notes', { body, kind: 'EVIDENCE', evidence_reference: ref }, 'Evidence attached')} />
      <ResolveDialog open={dlg === 'resolve'} onClose={() => setDlg(null)} onSubmit={(notes, next) => act('resolve', { repair_notes: notes, next_maintenance_due: next }, 'Repair recorded')} />
      <ConfirmDialog open={dlg === 'verify'} onClose={() => setDlg(null)} title="Verify equipment operation" description="Confirm the unit is holding its approved temperature range."
        reasonLabel="Verification notes" confirmLabel="Verify" onConfirm={(n) => act('verify', { ok: true, notes: n || undefined }, 'Verified')} />
      <ConfirmDialog open={dlg === 'fail'} onClose={() => setDlg(null)} title="Verification failed" danger reasonLabel="What is still wrong?" reasonRequired minReason={3}
        confirmLabel="Send back to technician" onConfirm={(n) => act('verify', { ok: false, notes: n }, 'Returned to technician')} />
      <ConfirmDialog open={dlg === 'close'} onClose={() => setDlg(null)} title="Close work order" reasonLabel="Closing notes" confirmLabel="Close"
        onConfirm={(n) => act('close', { notes: n || undefined }, 'Closed')} />
    </>
  )
}

function AssignTech({ open, onClose, facilityId, onSubmit }: { open: boolean; onClose: () => void; facilityId: string; onSubmit: (id: string) => Promise<unknown> }) {
  const techs = useApi(() => Users.assignable('TECHNICIAN', facilityId), [facilityId, open], { enabled: open })
  const [sel, setSel] = useState('')
  return (
    <Modal open={open} onClose={onClose} title="Assign technician" size="sm"
      footer={<><button className="btn-secondary" onClick={onClose}>Cancel</button><button className="btn-primary" disabled={!sel} onClick={async () => { try { await onSubmit(sel); onClose() } catch { /* */ } }}>Assign</button></>}>
      <select className="input" value={sel} onChange={(e) => setSel(e.target.value)}>
        <option value="">Select technician…</option>{(techs.data || []).map((u) => <option key={u.id} value={u.id}>{u.name}</option>)}
      </select>
      {techs.data && !techs.data.length && <p className="text-xs text-ink-3 mt-2">No technicians are assigned to this facility.</p>}
    </Modal>
  )
}

function EvidenceDialog({ open, onClose, onSubmit }: { open: boolean; onClose: () => void; onSubmit: (b: string, r: string) => Promise<unknown> }) {
  const [body, setBody] = useState('')
  const [ref, setRef] = useState('')
  return (
    <Modal open={open} onClose={onClose} title="Attach maintenance evidence" size="sm" description="Reference a photo, document or certificate stored in your document system."
      footer={<><button className="btn-secondary" onClick={onClose}>Cancel</button><button className="btn-primary" disabled={body.length < 2 || !ref} onClick={async () => { try { await onSubmit(body, ref); onClose() } catch { /* */ } }}>Attach</button></>}>
      <div className="space-y-3">
        <Field label="Description" required><input className="input" value={body} onChange={(e) => setBody(e.target.value)} /></Field>
        <Field label="Evidence reference / URL" required><input className="input" value={ref} onChange={(e) => setRef(e.target.value)} placeholder="e.g. DMS-2026-0412.jpg" /></Field>
      </div>
    </Modal>
  )
}

function ResolveDialog({ open, onClose, onSubmit }: { open: boolean; onClose: () => void; onSubmit: (n: string, next?: string) => Promise<unknown> }) {
  const [notes, setNotes] = useState('')
  const [next, setNext] = useState('')
  return (
    <Modal open={open} onClose={onClose} title="Record repair"
      footer={<><button className="btn-secondary" onClick={onClose}>Cancel</button><button className="btn-primary" disabled={notes.length < 5}
        onClick={async () => { try { await onSubmit(notes, next ? new Date(next).toISOString() : undefined); onClose() } catch { /* */ } }}>Mark resolved</button></>}>
      <div className="space-y-3">
        <Field label="Repair performed" required><textarea className="input h-24 py-2" value={notes} onChange={(e) => setNotes(e.target.value)} /></Field>
        <Field label="Next maintenance due"><input type="date" className="input" value={next} onChange={(e) => setNext(e.target.value)} /></Field>
      </div>
    </Modal>
  )
}
